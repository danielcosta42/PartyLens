UI.TRANSLATIONS = { ptBR = ptBR }

local locale = GetLocale and GetLocale() or "enUS"
local mine = UI.TRANSLATIONS[locale]

local core = rawget(_G, "PartyLens")
if type(core) == "table" and type(core.AddStrings) == "function" then
	for loc, strings in pairs(UI.TRANSLATIONS) do core:AddStrings(loc, strings) end
end

local function Lookup(key)
	local pl = rawget(_G, "PartyLens")
	local strings = type(pl) == "table" and type(pl.L) == "table" and pl.L
	if strings then
		local v = strings[key]
		if type(v) == "string" and v ~= "" and v ~= key then return v end
	end
	return mine and mine[key] or key
end

UI.L = setmetatable({}, {
	__index = function(t, key)
		local v = Lookup(key)
		rawset(t, key, v)
		return v
	end,
})
